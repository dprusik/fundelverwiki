    await page.waitForFunction(() => document.querySelector('#decision-feedback').textContent.includes('Uzupełnij publiczny tytuł'));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByLabel('Główna sekcja', { exact: true }).selectOption('characters');
    await page.getByLabel('Rodzaj encji', { exact: true }).selectOption('character');
    assert.equal(await page.evaluate(() => window.syntheticLeak), undefined);
    assert.equal(await page.locator('#preview button').filter({ hasText: 'src/site/img/dot.png' }).count(), 1);
    await page.getByRole('checkbox', { name: 'Zaznacz src/site/notes/example.md', exact: true }).check();
    await page.locator('#confirm-review').check(); await page.locator('#approve').click();
    await page.waitForFunction(() => document.querySelector('#message').textContent.includes('Zapisano 1'));
    assert.ok((await page.locator('#decision-feedback').textContent()).includes('Zapisano 1 nowych decyzji'));
    await page.locator('#kind').selectOption('asset');
