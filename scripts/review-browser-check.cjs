    assert.equal(review.list().find(item => item.kind === 'entry').state, 'approved');
    // Technical batch: each source opened, never approved merely by selecting a folder.
    await page.locator('#state').selectOption(''); await page.locator('#kind').selectOption('system');
    await page.getByRole('button', { name: 'src/site/_data/first.js', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#preview h2').textContent.includes('first.js'));
    await page.getByRole('button', { name: 'src/site/_data/second.js', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#preview h2').textContent.includes('second.js'));
    await page.locator('#select-visible').click(); await page.locator('#confirm-review').check(); await page.locator('#approve').click();
    await page.waitForFunction(() => document.querySelector('#message').textContent.includes('Zapisano 2'));
    write('src/site/notes/example.md', note.replace('Original synthetic text', 'Changed synthetic text'));
    await page.locator('#refresh').click(); await page.locator('#kind').selectOption('entry');
    await page.getByRole('button', { name: 'src/site/notes/example.md', exact: true }).click();
    await page.waitForSelector('#preview .add');
    await page.locator('#return-to-list').click();
    assert.ok((await page.locator('#preview .add').allTextContents()).some(text => text.includes('Changed synthetic text')));
    await page.getByRole('checkbox', { name: 'Zaznacz src/site/notes/example.md', exact: true }).check();
