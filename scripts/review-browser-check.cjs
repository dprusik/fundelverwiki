    assert.equal(review.events().length, 5);
    assert.equal(review.events()[0].decision, 'approved');
    assert.equal(review.events().at(-1).decision, 'denied');
    await page.locator('#export').click();
    await page.waitForFunction(() => document.querySelector('#message').textContent.includes('Propozycje:'));
    assert.deepEqual(fs.readFileSync(path.join(root, 'src/wiki/public-entries.json')), registryBefore);
    assert.deepEqual(errors, []);
