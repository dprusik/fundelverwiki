    assert.ok((await page.locator('#decision-feedback').textContent()).includes('Najpierw otwórz podgląd'));
    assert.equal(createReview(root, { store: path.join(root, '.publication-review') }).events().length, 0);
    await page.locator('#clear-selection').click();
    await page.getByRole('button', { name: 'src/site/notes/example.md', exact: true }).click();
    await page.locator('#return-to-list').click();
    await page.getByRole('checkbox', { name: 'Zaznacz src/site/notes/example.md', exact: true }).check();
    await page.locator('#confirm-review').check();
